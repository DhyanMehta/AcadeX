CREATE TYPE user_role_enum AS ENUM ('student', 'faculty', 'coordinator');
CREATE TYPE attendance_status_enum AS ENUM ('present', 'absent', 'late');
CREATE TYPE exam_type_enum AS ENUM ('unit_test_1', 'unit_test_2', 'mid_sem', 'practical', 'assignment', 'viva', 'end_sem');
CREATE TYPE submission_status_enum AS ENUM ('pending', 'graded', 'missing');
CREATE TYPE risk_label_enum AS ENUM ('low', 'medium', 'high', 'critical');
CREATE TYPE alert_type_enum AS ENUM ('high_risk', 'critical_risk', 'attendance_drop', 'marks_drop', 'assignment_overdue', 'lms_inactive');
CREATE TYPE intervention_type_enum AS ENUM ('counselling', 'remedial_class', 'assignment_extension', 'parent_meeting', 'academic_support', 'other');

CREATE OR REPLACE FUNCTION set_updated_at()
RETURNS TRIGGER AS $$
BEGIN
  NEW.updated_at = NOW();
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TABLE departments (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(150) NOT NULL,
  code VARCHAR(20) NOT NULL UNIQUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE users (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(150) NOT NULL,
  email VARCHAR(255) NOT NULL UNIQUE,
  password_hash VARCHAR(255) NOT NULL,
  role user_role_enum NOT NULL,
  department_id INTEGER NULL REFERENCES departments(id) ON UPDATE CASCADE ON DELETE RESTRICT,
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX idx_users_role ON users(role);
CREATE INDEX idx_users_department ON users(department_id);

CREATE TABLE classes (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(100) NOT NULL,
  semester SMALLINT NOT NULL CHECK (semester BETWEEN 1 AND 8),
  department_id INTEGER NOT NULL REFERENCES departments(id) ON UPDATE CASCADE ON DELETE RESTRICT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX idx_classes_department ON classes(department_id);
CREATE INDEX idx_classes_semester ON classes(semester);

CREATE TABLE students (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INTEGER NOT NULL UNIQUE REFERENCES users(id) ON UPDATE CASCADE ON DELETE RESTRICT,
  enrollment_no VARCHAR(30) NOT NULL UNIQUE,
  class_id INTEGER NOT NULL REFERENCES classes(id) ON UPDATE CASCADE ON DELETE RESTRICT,
  mentor_id INTEGER NOT NULL REFERENCES users(id) ON UPDATE CASCADE ON DELETE RESTRICT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX idx_students_class ON students(class_id);
CREATE INDEX idx_students_mentor ON students(mentor_id);

CREATE TABLE subjects (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(150) NOT NULL,
  code VARCHAR(20) NOT NULL,
  class_id INTEGER NOT NULL REFERENCES classes(id) ON UPDATE CASCADE ON DELETE RESTRICT,
  teacher_id INTEGER NOT NULL REFERENCES users(id) ON UPDATE CASCADE ON DELETE RESTRICT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE (code, class_id)
);

CREATE INDEX idx_subjects_class ON subjects(class_id);
CREATE INDEX idx_subjects_teacher ON subjects(teacher_id);

CREATE TABLE attendance_records (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  student_id INTEGER NOT NULL REFERENCES students(id) ON UPDATE CASCADE ON DELETE CASCADE,
  subject_id INTEGER NOT NULL REFERENCES subjects(id) ON UPDATE CASCADE ON DELETE RESTRICT,
  "date" DATE NOT NULL,
  status attendance_status_enum NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE (student_id, subject_id, "date")
);

CREATE INDEX idx_attendance_subject ON attendance_records(subject_id);
CREATE INDEX idx_attendance_date ON attendance_records("date");

CREATE TABLE internal_marks (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  student_id INTEGER NOT NULL REFERENCES students(id) ON UPDATE CASCADE ON DELETE CASCADE,
  subject_id INTEGER NOT NULL REFERENCES subjects(id) ON UPDATE CASCADE ON DELETE RESTRICT,
  entered_by INTEGER NOT NULL REFERENCES users(id) ON UPDATE CASCADE ON DELETE RESTRICT,
  exam_type exam_type_enum NOT NULL,
  marks_obtained NUMERIC(6,2) NULL,
  max_marks NUMERIC(6,2) NOT NULL CHECK (max_marks > 0),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE (student_id, subject_id, exam_type),
  CHECK (marks_obtained IS NULL OR marks_obtained <= max_marks)
);

CREATE INDEX idx_marks_subject ON internal_marks(subject_id);
CREATE INDEX idx_marks_entered_by ON internal_marks(entered_by);

CREATE TABLE assignments (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  subject_id INTEGER NOT NULL REFERENCES subjects(id) ON UPDATE CASCADE ON DELETE RESTRICT,
  title VARCHAR(255) NOT NULL,
  due_date DATE NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX idx_assignments_subject ON assignments(subject_id);
CREATE INDEX idx_assignments_due_date ON assignments(due_date);

CREATE TABLE assignment_submissions (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  assignment_id INTEGER NOT NULL REFERENCES assignments(id) ON UPDATE CASCADE ON DELETE RESTRICT,
  student_id INTEGER NOT NULL REFERENCES students(id) ON UPDATE CASCADE ON DELETE CASCADE,
  entered_by INTEGER NULL REFERENCES users(id) ON UPDATE CASCADE ON DELETE SET NULL,
  status submission_status_enum NOT NULL DEFAULT 'pending',
  marks_obtained NUMERIC(6,2) NULL,
  max_marks NUMERIC(6,2) NOT NULL CHECK (max_marks > 0),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE (assignment_id, student_id),
  CHECK (marks_obtained IS NULL OR marks_obtained <= max_marks)
);

CREATE INDEX idx_submission_student ON assignment_submissions(student_id);
CREATE INDEX idx_submission_entered_by ON assignment_submissions(entered_by);
CREATE INDEX idx_submission_status ON assignment_submissions(status);

CREATE TABLE lms_activity (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  student_id INTEGER NOT NULL REFERENCES students(id) ON UPDATE CASCADE ON DELETE CASCADE,
  subject_id INTEGER NOT NULL REFERENCES subjects(id) ON UPDATE CASCADE ON DELETE RESTRICT,
  activity_date DATE NOT NULL,
  logins SMALLINT NOT NULL DEFAULT 0 CHECK (logins >= 0),
  activity_score NUMERIC(5,2) NOT NULL DEFAULT 0.00 CHECK (activity_score >= 0 AND activity_score <= 100),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE (student_id, subject_id, activity_date)
);

CREATE INDEX idx_lms_subject ON lms_activity(subject_id);
CREATE INDEX idx_lms_date ON lms_activity(activity_date);

CREATE TABLE risk_scores (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  student_id INTEGER NOT NULL REFERENCES students(id) ON UPDATE CASCADE ON DELETE CASCADE,
  attendance_pct NUMERIC(5,2) NOT NULL CHECK (attendance_pct BETWEEN 0 AND 100),
  marks_pct NUMERIC(5,2) NOT NULL CHECK (marks_pct BETWEEN 0 AND 100),
  assignment_pct NUMERIC(5,2) NOT NULL CHECK (assignment_pct BETWEEN 0 AND 100),
  lms_score NUMERIC(5,2) NOT NULL CHECK (lms_score BETWEEN 0 AND 100),
  risk_score NUMERIC(5,2) NOT NULL CHECK (risk_score BETWEEN 0 AND 100),
  risk_label risk_label_enum NOT NULL,
  ai_explanation TEXT NOT NULL,
  ai_suggestions TEXT NOT NULL,
  model_version VARCHAR(20) NOT NULL,
  computed_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX idx_risk_student ON risk_scores(student_id);
CREATE INDEX idx_risk_label ON risk_scores(risk_label);
CREATE INDEX idx_risk_computed_at ON risk_scores(computed_at);
CREATE INDEX idx_risk_student_time ON risk_scores(student_id, computed_at);

CREATE TABLE alerts (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  student_id INTEGER NOT NULL REFERENCES students(id) ON UPDATE CASCADE ON DELETE CASCADE,
  mentor_id INTEGER NOT NULL REFERENCES users(id) ON UPDATE CASCADE ON DELETE RESTRICT,
  alert_type alert_type_enum NOT NULL,
  is_read BOOLEAN NOT NULL DEFAULT FALSE,
  triggered_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX idx_alerts_student ON alerts(student_id);
CREATE INDEX idx_alerts_mentor ON alerts(mentor_id);
CREATE INDEX idx_alerts_is_read ON alerts(is_read);
CREATE INDEX idx_alerts_type ON alerts(alert_type);
CREATE INDEX idx_alerts_triggered ON alerts(triggered_at);
CREATE INDEX idx_alerts_mentor_read ON alerts(mentor_id, is_read);

CREATE TABLE interventions (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  student_id INTEGER NOT NULL REFERENCES students(id) ON UPDATE CASCADE ON DELETE CASCADE,
  mentor_id INTEGER NOT NULL REFERENCES users(id) ON UPDATE CASCADE ON DELETE RESTRICT,
  "type" intervention_type_enum NOT NULL,
  remarks TEXT NOT NULL,
  risk_score_before NUMERIC(5,2) NOT NULL CHECK (risk_score_before BETWEEN 0 AND 100),
  conducted_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX idx_interventions_student ON interventions(student_id);
CREATE INDEX idx_interventions_mentor ON interventions(mentor_id);
CREATE INDEX idx_interventions_type ON interventions("type");
CREATE INDEX idx_interventions_conducted ON interventions(conducted_at);

CREATE TABLE intervention_outcomes (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  intervention_id INTEGER NOT NULL UNIQUE REFERENCES interventions(id) ON UPDATE CASCADE ON DELETE CASCADE,
  student_id INTEGER NOT NULL REFERENCES students(id) ON UPDATE CASCADE ON DELETE CASCADE,
  risk_score_before NUMERIC(5,2) NOT NULL CHECK (risk_score_before BETWEEN 0 AND 100),
  risk_score_after NUMERIC(5,2) NOT NULL CHECK (risk_score_after BETWEEN 0 AND 100),
  risk_label_before risk_label_enum NOT NULL,
  risk_label_after risk_label_enum NOT NULL,
  measured_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX idx_outcome_student ON intervention_outcomes(student_id);
CREATE INDEX idx_outcome_label_after ON intervention_outcomes(risk_label_after);

